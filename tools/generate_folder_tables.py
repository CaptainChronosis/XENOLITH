"""Independent static diode/op-amp cascade tables for Xenolith.

Circuit equation from Esqueda et al., Applied Sciences 2017, 7, 1328,
section 3: x = v + 2 R Is sinh(v/(eta VT)); output = 2v-x.
Use the complete antiparallel Shockley pair, solved offline by bisection.
No runtime circuit solver or copied third-party implementation.
"""
from pathlib import Path
import argparse
import math
import struct

COUNT = 256
LIMIT = 6.0
STAGES = (1, 2, 4, 6)


def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]


def cell(x):
    sign = -1.0 if x < 0 else 1.0
    x = abs(x)
    lo, hi = 0.0, min(x, 1.0)
    for _ in range(64):
        v = (lo + hi) * 0.5
        if v + 2 * 33000 * 2.52e-9 * math.sinh(v / (1.752 * .025864)) > x:
            hi = v
        else:
            lo = v
    return sign * (lo + hi - x)


def cascade(x, stages):
    for _ in range(stages):
        x = cell(x)
    return x


def tables():
    curves, integrals = [], []
    for stages in STAGES:
        curve = [f32(cascade(LIMIT * i / COUNT, stages)) for i in range(COUNT + 1)]
        integral = [0.0]
        area = 0.0
        for a, b in zip(curve, curve[1:]):
            area += .5 * (a + b) * LIMIT / COUNT
            integral.append(f32(area))
        curves.append(curve)
        integrals.append(integral)
    return curves, integrals


def generated():
    result = '/* SPDX-License-Identifier: MPL-2.0\n * Generated by tools/generate_folder_tables.py; positive half of odd curves.\n * 1/2/4/6 static diode/op-amp cascades; domain0..6; exact PL integrals. */\n'
    for name, rows in zip(('folder_curve', 'folder_integral'), tables()):
        result += f'static const float {name}[4][257]={{\n'
        for row in rows:
            result += ' {\n'
            for i in range(0, len(row), 4):
                result += '  ' + ','.join(float.hex(v) + 'f' for v in row[i:i+4]) + ',\n'
            result += ' },\n'
        result += '};\n'
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / 'app/xenolith_folder_tables.inc'
    content = generated()
    if args.check:
        if target.read_text() != content:
            raise SystemExit('Folder table generation mismatch')
        print('Folder table generation matches')
    else:
        target.write_text(content)
