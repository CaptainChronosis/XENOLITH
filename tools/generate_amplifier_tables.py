"""Generate deterministic float32 transfer tables; no sampled hardware data.

SPACE3/2: 2*((x+1.5)/3)**1.5-1, x in[-1.5,1.5]. Its exponent is inspired
by the idealized three-halves triode law; this normalized waveshaper is not a
tube circuit simulation. SOFTSIGN: (5/3)*x/(1+abs(x)), normalized at x=1.5.
257 samples permit linear interpolation with one multiply and two table reads.
"""
from pathlib import Path
import argparse
import struct


def generated():
    text='/* SPDX-License-Identifier: MPL-2.0\n * Generated by tools/generate_amplifier_tables.py.\n * Domain[-1.5,1.5],257 endpoints, float32; generic transfer functions.\n */\n'
    for name,fn in [('amp_space32',lambda x:2*((x+1.5)/3)**1.5-1),
                    ('amp_softsign',lambda x:(5/3)*x/(1+abs(x)))]:
        values=[float.hex(struct.unpack('<f',struct.pack('<f',fn(-1.5+3*i/256)))[0])+'f' for i in range(257)]
        text+='static const float '+name+'[257]={\n'
        for i in range(0,257,4):text+='    '+','.join(values[i:i+4])+(',' if i+4<257 else '')+'\n'
        text+='};\n'
    return text


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    path=Path(__file__).resolve().parents[1]/'app/xenolith_amplifier_tables.inc'
    text=generated()
    if args.check:
        if path.read_text()!=text:raise SystemExit('Amplifier table generation mismatch')
        print('Amplifier table generation matches')
    else:path.write_text(text)
