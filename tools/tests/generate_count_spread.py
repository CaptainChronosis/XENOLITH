"""Freeze count-only spread and density formulas as exact float coefficients.

The preserved C implementation contains the seventh-order reduced exp2 and
symmetric jitter formula. Compile it with the same no-contraction host policy
as the core regression, evaluate every9..64-cell row and1..64 density endpoint,
and emit exact hex floats. The density fade grid remains independent.
Run from any directory; --check verifies the checked-in generated include.
"""
from pathlib import Path
import argparse,hashlib,struct,subprocess,tempfile
TESTS=Path(__file__).resolve().parent
PROJECT=TESTS.parents[1]
REFERENCE=TESTS/'fixtures/count_kernel/core_before.c'
OUTPUT=PROJECT/'app/xenolith_count_spread.inc'

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    with tempfile.TemporaryDirectory(prefix='xx29_count_spread_') as directory:
        folder=Path(directory);source=folder/'generate.c';exe=folder/'generate.exe'
        source.write_text('#include <stdio.h>\n#include <string.h>\n#ifdef _WIN32\n#include <io.h>\n#include <fcntl.h>\n#endif\n'
            '#include "'+REFERENCE.as_posix()+'"\n'
            'int main(void){XenolithCore s;unsigned n;memset(&s,0,sizeof s);\n'
            '#ifdef _WIN32\n_setmode(_fileno(stdout),_O_BINARY);\n#endif\n'
            'for(n=9;n<=64;n++){s.cells=n;prepare_spread(&s);fwrite(s.spread_scale,sizeof(float),n,stdout);}'
            'for(n=1;n<=64;n++){float value=density_gain(n);fwrite(&value,sizeof value,1,stdout);}'
            'return ferror(stdout)?1:0;}\n')
        subprocess.run(['gcc','-std=c11','-O2','-ffp-contract=off',str(source),'-I'+str(PROJECT/'app'),'-o',str(exe)],check=True,capture_output=True)
        data=subprocess.check_output([str(exe)])
    assert len(data)==(2044+64)*4
    values=iter(struct.unpack('<2044f',data[:2044*4]))
    lines=['/* Generated by tools/tests/generate_count_spread.py.',
           ' * Original count-spread formula SHA256: '+hashlib.sha256(REFERENCE.read_bytes()).hexdigest(),
           ' * Counts9..64, contiguous triangular rows; exact float32 values. */',
           'static const float count_spread_table[2044]={']
    for count in range(9,65):
        lines.append(f'    /* {count} cells */')
        row=[next(values).hex()+'f' for _ in range(count)]
        for offset in range(0,count,4):lines.append('    '+','.join(row[offset:offset+4])+',')
    lines.append('};')
    lines.append('/* Exact five-step Newton endpoints; distinct from the fade grid. */')
    lines.append('static const float count_density_target[64]={')
    density=[value.hex()+'f' for value in struct.unpack('<64f',data[2044*4:])]
    for offset in range(0,64,4):lines.append('    '+','.join(density[offset:offset+4])+',')
    lines.append('};')
    text='\n'.join(lines)+'\n'
    if args.check:
        if OUTPUT.read_text()!=text:raise SystemExit('Count spread table differs from preserved formula')
    else:OUTPUT.write_text(text)
    print(f'{"Verified" if args.check else "Generated"}: {OUTPUT}; {len(data)} coefficient bytes')

if __name__=='__main__':main()
