"""Rasterize Xenolith's pinned VT323 into the fm1-base 4-bit font ABI.

Encoding follows Charles Vestal and Leo Kuroshita's MPL-2.0 gen_font.py.
The embedded font data remains SIL OFL 1.1: see assets/fonts/OFL.txt.
Only this app's generated header is replaced; the framework is unchanged.
Pillow BASIC layout avoids an optional libraqm dependency. VT323 is already
monospaced, so no OpenType tabular-figure shaping feature is necessary.
"""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, __version__ as PILLOW_VERSION

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "assets" / "fonts" / "VT323-Regular.ttf"
FONT_SHA256 = "cf4de751ada78ceac033dbe16a687742939995b77bc2a052ae17a4957958594d"
PAD = 2
# role, raster pixels, top crop, cell height, ASCII last, fixed advance.
# Advances retain the previous layout; the extra height belongs to the face.
ROLES = (("T", 16, 1, 15, 95, 6), ("XS", 16, 1, 15, 126, 6),
         ("S", 20, 2, 18, 126, 8), ("B", 20, 2, 18, 126, 8),
         ("M", 30, 3, 27, 95, 12), ("L", 40, 5, 35, 95, 16))


def render(role):
    name, size, top, height, last, expected_advance = role
    font = ImageFont.truetype(str(FONT), size, layout_engine=ImageFont.Layout.BASIC)
    glyphs = []
    for code in range(32, last + 1):
        char = chr(code)
        advance = round(font.getlength(char))
        if advance != expected_advance:
            raise ValueError(f"{name}: unexpected advance for {char!r}: {advance}")
        width = advance + 2 * PAD
        # Render with enough surrounding rows to detect any accidental clipping.
        original = Image.new("L", (width, size * 2), 0)
        ImageDraw.Draw(original).text((PAD, 0), char, font=font, fill=255)
        bounds = original.getbbox()
        if bounds and (bounds[1] < top or bounds[3] > top + height):
            raise ValueError(f"{name}: glyph {char!r} would be clipped: {bounds}")
        cropped = original.crop((0, top, width, top + height))
        pixels = [min(15, (value + 8) // 17) for value in cropped.tobytes()]
        glyphs.append((advance, width, pixels))
    return height, glyphs


def generate(output):
    if hashlib.sha256(FONT.read_bytes()).hexdigest() != FONT_SHA256:
        raise SystemExit("VT323 font hash mismatch; inspect FONT_PROVENANCE.json before replacing it")
    lines = ["/* Xenolith-specific VT323; generated by tools/gen_vt323.py.",
             " * Font data: Copyright 2011 The VT323 Project Authors, SIL OFL 1.1.",
             " * Retain assets/fonts/OFL.txt with distributed source. */",
             "#pragma once", "#include <stdint.h>", f"#define FONT_PAD {PAD}", ""]
    report = {"font_sha256": FONT_SHA256, "pillow": PILLOW_VERSION,
              "layout_engine": "BASIC", "alpha_bits": 4, "roles": []}
    for role in ROLES:
        name, size, top, height, last, advance = role
        height, glyphs = render(role)
        data, offsets = [], []
        for adv, width, pixels in glyphs:
            offsets.append(len(data))
            for y in range(height):
                row = pixels[y * width:(y + 1) * width] + [0]
                data.extend((row[x] << 4) | row[x + 1] for x in range(0, width, 2))
        if len(data) >= 65536:
            raise ValueError(f"{name}: uint16 font offsets overflow")
        lines.append(f"static const uint8_t FONT_{name}_DATA[{len(data)}] = {{")
        lines.extend("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ","
                     for i in range(0, len(data), 24))
        lines.append("};")
        for kind, c_type, values in (("OFF", "uint16_t", offsets),
                                      ("ADV", "uint8_t", [g[0] for g in glyphs]),
                                      ("BW", "uint8_t", [g[1] for g in glyphs])):
            lines.append(f"static const {c_type} FONT_{name}_{kind}[{len(values)}] = {{" +
                         ", ".join(map(str, values)) + "};")
        lines.append(f"static const felucca_font_t FONT_{name} = {{ {height}, {PAD}, 32, {last}, "
                     f"FONT_{name}_ADV, FONT_{name}_BW, FONT_{name}_OFF, FONT_{name}_DATA }};")
        lines.append("")
        row = {"role": name, "raster_px": size, "crop_top": top, "height": height,
               "advance": advance, "glyphs": len(glyphs), "bitmap_bytes": len(data),
               "metric_bytes": len(glyphs) * 4}
        report["roles"].append(row)
        print(f"VT323 {name}: {size}px / h{height} / advance{advance} / {len(data)} bitmap bytes")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    report["all_roles_bitmap_bytes"] = sum(r["bitmap_bytes"] for r in report["roles"])
    report["all_roles_metric_bytes"] = sum(r["metric_bytes"] for r in report["roles"])
    report["header_sha256"] = hashlib.sha256(output.read_bytes()).hexdigest()
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    result = generate(args.output)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
